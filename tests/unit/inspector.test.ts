import {test} from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {runInNewContext} from "node:vm";

test("inspector registers and saves against its own UUID, preserving profile identity", () => {
  const elements = new Map<string, any>();
  const element = (id: string) => {
    if (!elements.has(id)) elements.set(id, {value: "", dataset: {}, classList: {toggle() {}}, replaceChildren() {}});
    return elements.get(id);
  };
  let socket: any;
  const sent: any[] = [];
  class Socket {
    static OPEN = 1;
    readyState = 1;
    constructor() {socket = this;}
    send(data: string) {sent.push(JSON.parse(data));}
  }
  const window: any = {};
  runInNewContext(readFileSync("com.firflabs.wootdeck.sdPlugin/ui/settings.js","utf8"), {
    window, document: {getElementById: element}, WebSocket: Socket,
    Option: class {constructor(public text: string, public value: string) {}},
    setInterval() {},
  });
  window.connectElgatoStreamDeckSocket(1234, "inspector-id", "registerPropertyInspector", "{}", JSON.stringify({context:"different-action-context",action:"com.firflabs.wootdeck.select",payload:{settings:{}}}));
  socket.onopen();
  socket.onmessage({data: JSON.stringify({event:"sendToPropertyInspector",payload:{type:"inventory",devices:[{serial:"chosen",name:"Wooting",ready:true,profiles:[{slot:1,name:"Gaming"}],activeSlot:0}]}})});
  element("profile").value="1";
  element("profile").onchange();
  const saved = sent.filter(m=>m.event==="setSettings");
  assert.ok(saved.length>=2);
  assert.ok(saved.every(m=>m.context==="inspector-id"));
  assert.equal(saved.at(-1).payload.profileName,"Gaming");
  assert.equal(saved.at(-1).payload.serial,"chosen");
  assert.equal(saved.at(-1).payload.slot,1);
  assert.equal(element("direction").value,"1");
  assert.equal(element("long-direction").value,"-1");
  assert.equal(element("long-press-ms").value,500);
  element("direction").value="-1";element("direction").onchange();
  assert.equal(element("long-direction").value,"1");
  element("long-direction").value="-1";element("long-direction").onchange();
  element("long-press-ms").value="350";element("long-press-ms").onchange();
  assert.equal(sent.filter(m=>m.event==="setSettings").at(-1).payload.longDirection,-1);
  assert.equal(sent.filter(m=>m.event==="setSettings").at(-1).payload.longPressMs,350);
  element("long-press-ms").value="10";element("long-press-ms").onchange();
  assert.equal(element("long-press-ms").value,350);
  element("key").value="any";
  element("key").onchange();
  const anySettings=sent.filter(m=>m.event==="setSettings").at(-1).payload;
  assert.equal(anySettings.keyMode,"any");
  assert.equal(element("key").value,"any");
  assert.ok(!Number.isNaN(anySettings.key));
  element("key").value="custom";
  element("key").onchange();
  assert.equal(element("key").value,"custom");
  element("theme").value="amber";
  element("theme").onchange();
  const appearance=sent.filter(m=>m.event==="setSettings").at(-1).payload;
  assert.equal(appearance.theme,"amber");
  assert.ok(!readFileSync("com.firflabs.wootdeck.sdPlugin/ui/settings.html","utf8").includes('id="layout"'));
  assert.equal(appearance.serial,"chosen");
  assert.equal(element("depth-unit").value,"percent");
  element("depth-unit").value="mm";
  element("depth-unit").onchange();
  element("full-travel").value="3.5";
  element("full-travel").onchange();
  const units=sent.filter(m=>m.event==="setSettings").at(-1).payload;
  assert.equal(units.depthUnit,"mm");
  assert.equal(units.fullTravelMm,3.5);
  const saves=sent.length;
  element("full-travel").value="-2";
  element("full-travel").onchange();
  assert.equal(sent.length,saves);
  assert.equal(element("full-travel").value,3.5);
  assert.equal(element("depth-background").value,"theme");
  element("depth-background").value="three";
  element("depth-background").onchange();
  element("depth-color-mid").value="#123456";
  element("depth-color-mid").oninput();
  const colors=sent.filter(m=>m.event==="setSettings").at(-1).payload;
  assert.equal(colors.depthBackground,"three");
  assert.equal(colors.depthColorMid,"#123456");
  assert.equal(colors.depthUnit,"mm");
  assert.equal(element("profile-color-mode").value,"theme");
  element("profile-color-mode").value="custom";
  element("profile-color-mode").onchange();
  element("profile-active-background").value="#f01234";
  element("profile-active-background").oninput();
  const custom=sent.filter(m=>m.event==="setSettings").at(-1).payload;
  assert.equal(custom.profileColorMode,"custom");
  assert.equal(custom.profileActiveBackground,"#f01234");
  element("profile-color-mode").value="theme";
  element("profile-color-mode").onchange();
  assert.equal(sent.filter(m=>m.event==="setSettings").at(-1).payload.profileColorMode,"theme");
  element("background-mode").value="custom";
  element("background-mode").onchange();
  element("background-color").value="#123456";
  element("background-color").oninput();
  assert.equal(sent.filter(m=>m.event==="setSettings").at(-1).payload.backgroundColor,"#123456");
  element("theme").value="ice";
  element("theme").onchange();
  assert.equal(element("background-color").value,"#123456");
  element("background-mode").value="theme";
  element("background-mode").onchange();
  assert.equal(sent.filter(m=>m.event==="setSettings").at(-1).payload.backgroundMode,"theme");
  element("profile-pending-background").value="#123abc";
  element("profile-pending-background").oninput();
  assert.equal(sent.filter(m=>m.event==="setSettings").at(-1).payload.profilePendingBackground,"#123abc");
  assert.equal(element("box-theme").value,"solid");
  element("box-theme").value="corners";
  element("box-theme").onchange();
  assert.equal(sent.filter(m=>m.event==="setSettings").at(-1).payload.boxTheme,"corners");
  assert.equal(element("box-pixels").value,2);
  element("box-pixels").value="3";
  element("box-pixels").onchange();
  assert.equal(sent.filter(m=>m.event==="setSettings").at(-1).payload.boxPixels,3);
  element("box-theme").value="solid";
  element("box-theme").onchange();
  assert.equal(element("box-pixels").value,3);
  assert.equal(element("box-pixels-label").textContent,"Corner radius (px)");
  assert.equal(element("any-percent").checked,true);
  element("any-percent").checked=false;
  element("any-percent").onchange();
  assert.equal(sent.filter(m=>m.event==="setSettings").at(-1).payload.showAnyKeyPercent,false);
  assert.equal(element("font-family").value,"theme");
  assert.equal(element("font-weight").value,"bold");
  element("font-family").value="consolas";
  element("font-family").onchange();
  element("font-weight").value="normal";
  element("font-weight").onchange();
  const font=sent.filter(m=>m.event==="setSettings").at(-1).payload;
  assert.equal(font.fontFamily,"consolas");
  assert.equal(font.fontWeight,"normal");
  assert.equal(element("depth-foreground").value,"threshold");
  assert.equal(element("foreground-color-low").value,"#c5cbd3");
  assert.equal(element("foreground-color-high").value,"#39d98a");
  element("depth-foreground").value="three";
  element("depth-foreground").onchange();
  element("foreground-color-mid").value="#123abc";
  element("foreground-color-mid").oninput();
  const foreground=sent.filter(m=>m.event==="setSettings").at(-1).payload;
  assert.equal(foreground.depthForeground,"three");
  assert.equal(foreground.depthForegroundMid,"#123abc");
  socket.onmessage({data:JSON.stringify({event:"sendToPropertyInspector",payload:{type:"inventory",devices:[{serial:"chosen",name:"Wooting",ready:true,profiles:[{slot:0,name:"Typing"},{slot:1,name:"Gaming"}],activeSlot:0}],customThemes:[{id:"preset-one",name:"My design"}]}})});
  element("toggle-a").value="0";element("toggle-a").onchange();
  element("toggle-b").value="1";element("toggle-b").onchange();
  const toggle=sent.filter(m=>m.event==="setSettings").at(-1).payload;
  assert.equal(toggle.toggleSlotA,0);assert.equal(toggle.toggleNameA,"Typing");
  assert.equal(toggle.toggleSlotB,1);assert.equal(toggle.toggleNameB,"Gaming");
  element("any-filter").value="custom";element("any-filter").onchange();
  element("any-list").value="W, Space";element("any-list").onchange();
  assert.equal(sent.filter(m=>m.event==="setSettings").at(-1).payload.anyKeyList,"W, Space");
  element("show-threshold").checked=true;element("show-threshold").onchange();
  assert.equal(element("show-peak").checked,false);
  element("peak-reset").value="2.5";element("peak-reset").onchange();
  assert.equal(sent.filter(m=>m.event==="setSettings").at(-1).payload.peakResetSeconds,2.5);
  element("show-peak").checked=false;element("show-peak").onchange();
  assert.equal(sent.filter(m=>m.event==="setSettings").at(-1).payload.showPeak,false);
  element("peak-reset").value="-1";element("peak-reset").onchange();
  assert.equal(sent.filter(m=>m.event==="setSettings").at(-1).payload.peakResetSeconds,2.5);
  assert.equal(sent.filter(m=>m.event==="setSettings").at(-1).payload.showThreshold,true);
  element("refresh-actuation").onclick();
  assert.equal(sent.at(-1).payload.type,"refreshActuation");
  element("custom-theme").value="preset-one";element("custom-theme").onchange();
  element("theme-apply").onclick();
  assert.equal(sent.at(-1).payload.id,"preset-one");assert.equal(sent.at(-1).context,"inspector-id");
  element("custom-theme-name").value="My new design";element("theme-save").onclick();
  assert.equal(sent.at(-1).payload.type,"themeSave");assert.equal(sent.at(-1).payload.name,"My new design");
  assert.equal(element("active-background-mode").value,"inherit");
  element("active-background-mode").value="custom";element("active-background-mode").onchange();
  element("active-background-color").value="#00aa55";element("active-background-color").oninput();
  assert.equal(sent.filter(m=>m.event==="setSettings").at(-1).payload.activeBackgroundColor,"#00aa55");
  assert.equal(element("animation-mode").value,"crossfade");
  element("animation-mode").value="fade";element("animation-mode").onchange();
  element("animation-duration").value="600";element("animation-duration").onchange();
  element("animate-state").checked=false;element("animate-state").onchange();
  const animation=sent.filter(m=>m.event==="setSettings").at(-1).payload;
  assert.equal(animation.animation,"fade");assert.equal(animation.animationDuration,600);assert.equal(animation.animateState,false);
});
