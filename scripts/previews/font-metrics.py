"""Generate measured glyph bounds for the selectable Windows fonts and weights."""
from pathlib import Path
from PIL import ImageFont

families = {
    'segoe': ('segoeui.ttf', 'segoeuib.ttf'),
    'bahnschrift': ('bahnschrift.ttf', 'bahnschrift.ttf'),
    'arial': ('arial.ttf', 'arialbd.ttf'),
    'verdana': ('verdana.ttf', 'verdanab.ttf'),
    'tahoma': ('tahoma.ttf', 'tahomabd.ttf'),
    'consolas': ('consola.ttf', 'consolab.ttf'),
}
codes = list(range(32, 256)) + [0x2026, 0x2013, 0x2014]
rows = []
for family, files in families.items():
    for weight, name in zip((400, 700), files):
        font = ImageFont.truetype(str(Path('C:/Windows/Fonts') / name), 1000)
        if family == 'bahnschrift':
            font.set_variation_by_axes([weight, 100])
        rows.append(f'  "{family}-{weight}": {{')
        for code in codes:
            char = chr(code)
            box = font.getbbox(char, anchor='ls')
            width = max(font.getlength(char), box[2] - min(0, box[0])) / 1000
            above = max(0, -box[1]) / 1000
            below = max(0, box[3]) / 1000
            rows.append(f'    {code}:[{width:.4f},{above:.4f},{below:.4f}],')
        rows.append('  },')
Path('src/font-metrics.ts').write_text(
    '// SPDX-License-Identifier: GPL-3.0-or-later\n'
    '// Generated by scripts/previews/font-metrics.py; advance, ascent, descent in em.\n'
    'import type {Theme} from "./themes.js";\n'
    'const METRICS: Record<string, Record<number, readonly [number,number,number]>> = {\n'
    + '\n'.join(rows) + '\n};\n'
    'export function fontMetrics(theme:Theme):Record<number, readonly [number,number,number]> {\n'
    '  const family=theme.fontId || (theme.font.startsWith("Bahnschrift")?"bahnschrift":"segoe");\n'
    '  return METRICS[`${family}-${theme.fontWeight || 700}`] || METRICS["segoe-700"]!;\n'
    '}\n', encoding='utf-8')
